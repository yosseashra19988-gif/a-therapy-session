import streamlit as st
from test import aTherapySessions

# --- 1. MOODY, DISTURBING CLINICAL CSS ---
st.set_page_config(page_title="OBSERVATION_TERMINAL", page_icon="🩸", layout="centered")

st.markdown("""
    <style>
    /* Pure black background, monospace font to mimic a security terminal */
    .stApp {
        background-color: #050505;
        color: #a1a1aa;
        font-family: 'Courier New', Courier, monospace;
    }
    
    /* Blood red, sterile headers for the Sessions */
    h3 {
        color: #7f1d1d !important; 
        text-align: center;
        letter-spacing: 2px;
        border-bottom: 1px solid #1f1f22;
        padding-bottom: 10px;
        margin-top: 30px;
    }

    /* Therapist: Cold, calculated, left-aligned */
    .therapist-box {
        background-color: #0a0f18; 
        border-left: 3px solid #3b82f6; /* Cold blue */
        padding: 15px;
        margin-bottom: 10px;
        border-radius: 2px;
        font-size: 15px;
        color: #94a3b8;
    }
    
    /* Patient: Anxious, murky, right-aligned */
    .patient-box {
        background-color: #1a100f; 
        border-right: 3px solid #ef4444; /* Alert red */
        padding: 15px;
        margin-bottom: 10px;
        border-radius: 2px;
        text-align: right;
        font-size: 15px;
        color: #d6d3d1;
    }
    
    /* Blinking recording indicator */
    .blinking-cursor {
        color: #ef4444;
        animation: 1s blink step-end infinite;
    }
    @keyframes blink { 
        from, to { opacity: 1; }
        50% { opacity: 0; }
    }
    </style>
""", unsafe_allow_html=True)

# --- 2. TERMINAL HEADER ---
st.markdown("### 🔴 LIVE AUDIO TRANSCRIPT <span class='blinking-cursor'>[REC]</span>", unsafe_allow_html=True)

# --- 3. THE PARSING ENGINE ---
# We loop through the engine's last_message and style it based on who is speaking
for last_message in aTherapySessions():
    
    # Strip the markdown bolding generated by the engine for a cleaner look
    clean_text = last_message.replace("**", "")
    
    if "[Therapist]" in clean_text:
        # Wrap Therapist text in the cold blue CSS box
        st.markdown(f"<div class='therapist-box'>{clean_text}</div>", unsafe_allow_html=True)
        
    elif "[Patient]" in clean_text:
        # Wrap Patient text in the anxious red CSS box
        st.markdown(f"<div class='patient-box'>{clean_text}</div>", unsafe_allow_html=True)
        
    elif "STARTING DAY" in clean_text:
        # Format the session stamps as red headers
        header_text = clean_text.replace('### ', '')
        st.markdown(f"<h3>{header_text}</h3>", unsafe_allow_html=True)
        
    else:
        # Fallback for anything else
        st.write(clean_text)